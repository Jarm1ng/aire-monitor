def resolve_jobs(
    sections: dict[str, str],
    statuses: dict[str, int],
    user: str | None,
    now: datetime | None = None,
    rejects: list[str] | None = None,
) -> tuple[list[Job] | None, str | None, str]:
    """Pick the jobs source. Returns (jobs, source, note).

    source is "json", "pipe" or None (no usable jobs: a core failure). The
    note says why the JSON was not used ("" when it was), or, with no
    source, what failed.
    """
    json_status = statuses.get("jobs_json")
    if json_status == 0:
        jobs, problem = parse_jobs_json_checked(sections.get("jobs_json", ""), now=now, user=user)
        if jobs is not None:
            return jobs, "json", ""
        json_note = f"squeue --json {problem}"
    elif json_status is None:
        json_note = "squeue --json did not finish" if "jobs_json" in sections else "squeue --json did not run"
    else:
        json_note = f"squeue --json failed with exit {json_status}"

    pipe_status = statuses.get("jobs")
    if pipe_status == 0:
        return parse_jobs(sections.get("jobs", ""), sections.get("job_details", ""), rejects), "pipe", json_note
    if pipe_status is not None:
        return None, None, f"Section 'jobs' failed with exit {pipe_status} ({json_note})"
    if "jobs" in sections:
        return None, None, f"Section 'jobs' missing from remote output ({json_note})"
    if json_status == 0:
        # Usable-looking JSON that was not usable, and no pipe listing came
        # back (no budget left for the fallback, or it failed): an error, so
        # the next refresh retries instead of showing an empty queue.
        return None, None, f"No usable jobs listing ({json_note}; no pipe-format listing arrived)"
    return None, None, "Section 'jobs' missing from remote output"


def jobs_need_fallback_round_trip(output: str, user: str | None) -> bool:
    """True when the round trip finished jobs_json cleanly but its payload
    is unusable here and no pipe fallback ran remotely: the remote sanity
    check (a "jobs" key) passed, the local parse did not."""
    sections, statuses = split_sections(output)
    if statuses.get("jobs_json") != 0 or "jobs" in sections:
        return False
    return parse_jobs_json_checked(sections.get("jobs_json", ""), user=user)[0] is None


def describe_cut(sections: dict[str, str], statuses: dict[str, int]) -> str:
    """Where a timed-out round trip stopped: the section that had started
    but not finished, or the last one that finished."""
    unfinished = [name for name in sections if name not in statuses]
    if unfinished:
        return f"cut during {unfinished[-1]}"
    if statuses:
        return f"cut after {list(statuses)[-1]}"
    return "cut before any section finished"


def assemble_snapshot(
    config: SSHConfig,
    cluster: ClusterInfo,
    volumes: list[StorageVolume],
    collected_at: str,
    output: str,
    error: str | None,
    timed_out: bool,
    *,
    skip_storage: bool = False,
    now: datetime | None = None,
    started_at: str | None = None,
    duration_ms: int | None = None,
    local_timings: dict[str, int] | None = None,
) -> ClusterSnapshot:
    """Turn the raw remote output of a collection into a snapshot.

    Pure: `output` is everything the round trip(s) printed, `now` is the
    reference for running jobs' elapsed time (default: the local clock).
    """
    errors: list[str] = []
    warnings: list[str] = []
    sections, statuses = split_sections(output)
    remote = parse_remote_info(remote_host_label(config), sections.get("remote", ""))
    remote_user = remote.user or config.username

    job_rejects: list[str] = []
    jobs, jobs_source, jobs_note = resolve_jobs(sections, statuses, remote_user, now, job_rejects)

    core_complete = (
        bool(sections)
        and all(statuses.get(name) == 0 for name in CORE_SECTIONS)
        and jobs_source is not None
    )
    if error:
        # A timeout after every core section finished cleanly (typically a
        # hung filesystem stalling df/quota/lfs in the storage section, or a
        # slow scontrol show node) still yields a good snapshot; the stall is
        # reported as a warning naming the section that was cut.
        if timed_out and core_complete:
            warnings.append(f"{error} (core sections were complete; {describe_cut(sections, statuses)})")
        else:
            errors.append(error)
    elif not sections:
        # ssh succeeded yet not one section marker came back (e.g. a login
        # shell that is not POSIX sh): never pass that off as an empty but
        # healthy cluster.
        errors.append("Remote output contained no sections (the remote shell ran nothing)")

    if sections:
        for name in CORE_SECTIONS:
            code = statuses.get(name)
            if code is None:
                errors.append(f"Section '{name}' missing from remote output")
            elif code != 0:
                errors.append(f"Section '{name}' failed with exit {code}")
        if jobs_source is None:
            errors.append(jobs_note)
        elif jobs_source == "pipe":
            warnings.append(f"Jobs read with the pipe-format fallback ({jobs_note})")
        used_fallback = "jobs" in sections or "jobs" in statuses
        expected = [
            name for name in ENRICHMENT_SECTIONS
            if (name != "job_details" or used_fallback) and (name != "storage" or not skip_storage)
        ]
        for name in expected:
            code = statuses.get(name)
            if code is None:
                warnings.append(f"Section '{name}' missing from remote output")
            elif code != 0:
                warnings.append(f"Section '{name}' failed with exit {code}")

    partition_rejects: list[str] = []
    node_rejects: list[str] = []
    partitions = parse_partitions(sections.get("partitions", ""), partition_rejects)
    nodes = parse_nodes(sections.get("nodes", ""), sections.get("node_details", ""), node_rejects)
    for noun, rejected in (("job", job_rejects), ("partition", partition_rejects), ("node", node_rejects)):
        if rejected:
            warnings.append(
                f"Skipped {len(rejected)} unreadable {noun} line{'s' if len(rejected) != 1 else ''}: "
                f"{rejected[0][:120]!r}"
            )

    if sections and statuses.get("node_details") != 0:
        # Only nodes the failed/cut section left without a record: a node
        # whose complete record arrived is known, and one at a site without
        # GPU TRES is unknown for a reason no retry will fix.
        recorded = parse_node_details(sections.get("node_details", ""))
        unknown = sum(1 for node in nodes
                      if node.gpu_total and node.gpu_allocated is None and node.node not in recorded)
        if unknown:
            warnings.append(
                f"GPU allocation unknown for {unknown} GPU node{'s' if unknown != 1 else ''} "
                "(node_details unavailable)"
            )

    # Storage: None = not collected (skipped, busy, or the round trip never
    # reached the section), so the caller keeps its previous rows. A section
    # that started but was cut short still reports a row per volume.
    storage: list[StorageSummary] | None = None
    storage_skipped = skip_storage
    if not skip_storage and "storage" in sections:
        storage, storage_warnings = parse_storage(sections["storage"], volumes)
        warnings.extend(storage_warnings)
        if storage is None:
            storage_skipped = True

    timings = dict(local_timings or {})
    timings.update(section_timings(output))

    return ClusterSnapshot(
        collected_at=collected_at,
        cluster=cluster,
        remote=remote,
        jobs=jobs or [],
        partitions=partitions,
        nodes=nodes,
        storage=storage,
        errors=errors,
        warnings=warnings,
        storage_skipped=storage_skipped,
        started_at=started_at,
        duration_ms=duration_ms,
        timings=timings,
    )


def _elapsed_ms(start: float, end: float) -> int:
    return max(int(round((end - start) * 1000)), 0)


def collect_snapshot(
    config: SSHConfig,
    cluster: ClusterInfo,
    volumes: list[StorageVolume],
    skip_storage: bool = False,
) -> ClusterSnapshot:
    started_at = utc_now_iso()
    started = time.monotonic()
    # config.timeout is the budget for EVERYTHING below, so the collector
    # always prints its JSON before a caller watchdog of timeout + a few
    # seconds fires (the app: --timeout 30, 40 s watchdog). A hung storage
    # command then costs the storage rows (a warning), never the snapshot.
    deadline = started + config.timeout
    timings: dict[str, int] = {}

    probe_error = probe_master(config, timeout=min(PROBE_TIMEOUT, config.timeout))
    probed = time.monotonic()
    timings["probe"] = _elapsed_ms(started, probed)
    if probe_error:
        return empty_snapshot(config, cluster, utc_now_iso(), probe_error,
                              started_at=started_at, duration_ms=_elapsed_ms(started, probed),
                              timings=timings)

    remaining = max(1.0, deadline - time.monotonic())
    output, error, timed_out = run_ssh(
        config, build_remote_script(volumes, config.timeout, include_storage=not skip_storage),
        run_timeout=remaining,
    )
    returned = time.monotonic()
    timings["round_trip"] = _elapsed_ms(probed, returned)

    if error is None:
        remote_user = parse_remote_info("", split_sections(output)[0].get("remote", "")).user or config.username
        remaining = deadline - time.monotonic()
        if remaining >= MIN_FALLBACK_BUDGET and jobs_need_fallback_round_trip(output, remote_user):
            fallback_started = time.monotonic()
            fallback_output, fallback_error, fallback_timed_out = run_ssh(
                config, build_jobs_fallback_script(), run_timeout=remaining
            )
            # A failed fallback leaves 'jobs' missing or failed, which
            # resolve_jobs reports as the core error it is; its own error
            # (e.g. the budget ran out) is reported alongside.
            output = output + "\n" + fallback_output
            if fallback_error:
                error, timed_out = f"{fallback_error} (pipe-format jobs fallback)", fallback_timed_out
            returned = time.monotonic()
            timings["jobs_fallback_round_trip"] = _elapsed_ms(fallback_started, returned)

    return assemble_snapshot(
        config, cluster, volumes, utc_now_iso(), output, error, timed_out,
        skip_storage=skip_storage,
        started_at=started_at,
        duration_ms=_elapsed_ms(started, returned),
        local_timings=timings,
    )


def snapshot_payload(snapshot: ClusterSnapshot) -> dict[str, object]:
    """The JSON object printed on stdout: schema_version first, then the
    snapshot's fields in declaration order."""
    payload: dict[str, object] = {"schema_version": SCHEMA_VERSION}
    payload.update(asdict(snapshot))
    return payload


def run_self_test() -> int:
    """Run scripts/tests/test_snapshot.py, which loads THIS file by path.

    The tests live outside the production script so the collector stays
    readable; this flag remains for muscle memory and old instructions.
    """
    tests = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tests", "test_snapshot.py")
    if not os.path.isfile(tests):
        print(f"self-test: {tests} not found (the tests ship with the repository)", file=sys.stderr)
        return 2
    try:
        completed = subprocess.run([sys.executable, "-I", tests], check=False,
                                   stdin=subprocess.DEVNULL, timeout=600)
    except subprocess.TimeoutExpired:
        print("self-test: timed out after 600 s", file=sys.stderr)
        return 1
    return completed.returncode


def main() -> int:
    args = parse_args()
    if args.self_test:
        return run_self_test()

    cluster = ClusterInfo(
        id=args.cluster_id,
        name=args.cluster_name or default_cluster_name(args.cluster_id),
    )
    hostname = args.hostname
    if args.username and not hostname:
        hostname = KNOWN_CLUSTER_HOSTNAMES.get(args.cluster_id.lower())
    config = SSHConfig(
        host=args.host or args.cluster_id,
        username=args.username,
        hostname=hostname,
        use_jump_host=args.use_jump_host and not args.no_jump_host,
        jump_hostname=args.jump_hostname,
        control_path=args.control_path,
        jump_control_path=args.jump_control_path,
        timeout=args.timeout,
    )

    volumes, spec_error = parse_storage_spec(args.storage_spec)
    if spec_error:
        # Configuration bug, not a cluster problem: report it without
        # spending an SSH round trip on the shared login node.
        snapshot = empty_snapshot(config, cluster, utc_now_iso(), spec_error)
    else:
        try:
            snapshot = collect_snapshot(config, cluster, volumes, skip_storage=args.skip_storage)
        except Exception as exc:  # noqa: BLE001 - last line of defence
            # A collector bug must still produce JSON: with no stdout the app
            # can only say "snapshot script produced no output". The
            # traceback goes to stderr for debugging.
            traceback.print_exc(file=sys.stderr)
            snapshot = empty_snapshot(
                config,
                cluster,
                utc_now_iso(),
                f"Collector internal error: {type(exc).__name__}: {exc}",
            )

    indent = 2 if args.pretty else None
    payload = json.dumps(snapshot_payload(snapshot), indent=indent, ensure_ascii=False) + "\n"
    # Always UTF-8 (what the app decodes), whatever the caller's locale: a
    # non-UTF-8 locale must not turn a non-ASCII job name or a U+FFFD from
    # lenient decoding into a UnicodeEncodeError and an empty stdout.
    sys.stdout.buffer.write(payload.encode("utf-8"))
    sys.stdout.flush()
    return 1 if snapshot.errors else 0


if __name__ == "__main__":
    sys.exit(main())
