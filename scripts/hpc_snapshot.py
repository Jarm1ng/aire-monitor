def split_fields(line: str, expected: int) -> list[str] | None:
    fields = [part.strip() for part in line.split(FIELD_SEPARATOR)]
    if len(fields) != expected:
        return None
    return fields


def split_fields_last_free(line: str, expected: int) -> list[str] | None:
    """Split into exactly `expected` fields when the LAST one is free text.

    sinfo's %E (node Reason) is whatever an admin or a health check wrote,
    e.g. NHC's "check 'nvidia-smi -L | wc -l' returned 2". A bounded split
    lets it keep its '|' instead of the whole node vanishing.
    """
    fields = [part.strip() for part in line.split(FIELD_SEPARATOR, expected - 1)]
    if len(fields) != expected:
        return None
    return fields


def split_job_fields(line: str) -> list[str] | None:
    """Split a squeue '%i|%P|%j|%u|%T|%M|%l|%D|%R' line into 9 fields.

    Tolerates '|' characters inside the job name (%j) by splitting the last
    six fields from the right and the first two from the left.
    """
    parts = line.split(FIELD_SEPARATOR)
    if len(parts) == 9:
        return [part.strip() for part in parts]
    if len(parts) < 9:
        return None
    right = line.rsplit(FIELD_SEPARATOR, 6)
    left = right[0].split(FIELD_SEPARATOR, 2)
    if len(left) != 3:
        return None
    return [part.strip() for part in left + right[1:]]


def parse_int(value: str) -> int | None:
    value = value.strip()
    if not value or value in {"N/A", "n/a", "(null)"}:
        return None
    try:
        return int(value)
    except ValueError:
        return None


def parse_float(value: str) -> float | None:
    value = value.strip()
    if not value or value in {"N/A", "n/a", "(null)"}:
        return None
    try:
        return float(value)
    except ValueError:
        return None


def strip_quota_markers(value: str) -> tuple[str, bool]:
    """Strip trailing '*'/'+' over-quota markers appended by quota(1)/lfs."""
    stripped = value.strip()
    over_quota = stripped.endswith("*") or stripped.endswith("+")
    return stripped.rstrip("*+").strip(), over_quota


# Binary multipliers relative to GiB. quota -s and lfs -h both use powers of
# 1024 for space; raw lfs output and quota without -s are 1 KiB blocks.
_SIZE_TO_GIB = {
    "k": 1 / (1024 * 1024),
    "m": 1 / 1024,
    "g": 1.0,
    "t": 1024.0,
    "p": 1024.0 * 1024,
    "e": 1024.0 * 1024 * 1024,
}


def parse_size_to_gb(value: str, bare_unit: str = "k") -> float | None:
    """Convert a quota/lfs/df size token to GiB.

    Suffixed tokens ('45455M', '174.2G', '4k', '1.1T') use their suffix.
    Bare numbers are interpreted in `bare_unit` — KiB by default, which is
    what raw `lfs quota` and plain `quota` report.
    """
    value, _ = strip_quota_markers(value)
    if not value or value in {"N/A", "n/a", "(null)", "-"}:
        return None
    number = value
    suffix = bare_unit.lower()
    if value[-1].isalpha():
        number = value[:-1]
        suffix = value[-1].lower()
    try:
        amount = float(number)
    except ValueError:
        return None
    multiplier = _SIZE_TO_GIB.get(suffix)
    if multiplier is None:
        return None
    return amount * multiplier


def parse_percent(value: str) -> float | None:
    return parse_float(value.strip().rstrip("%"))


def parse_cpu_summary(value: str) -> tuple[int | None, int | None, int | None, int | None]:
    # sinfo %C returns allocated/idle/other/total.
    fields = value.split("/")
    if len(fields) != 4:
        return None, None, None, None
    return tuple(parse_int(field) for field in fields)  # type: ignore[return-value]


def parse_list(value: str) -> list[str]:
    cleaned = value.strip().rstrip("*")
    if not cleaned or cleaned in {"N/A", "(null)"}:
        return []
    return [item for item in cleaned.split(",") if item]


# scontrol -o keys are CamelCase words ('JobId=', 'ArrayTaskId=',
# 'CPUs/Task=', 'AllocNode:Sid='), always starting with a capital. Anything
# else containing '=' is part of the previous value: 'Command=run.sh --lr=0.1'
# and 'Command=run.sh lr=0.1' both keep their arguments.
KEY_TOKEN_RE = re.compile(r"^[A-Z][A-Za-z0-9_:/]*=")


def parse_key_values(line: str) -> dict[str, str]:
    result: dict[str, str] = {}
    current_key: str | None = None
    current_value: list[str] = []
    for token in line.split():
        if KEY_TOKEN_RE.match(token):
            key, value = token.split("=", 1)
            if current_key is not None:
                result[current_key] = " ".join(current_value)
            current_key = key
            current_value = [value]
        elif current_key is not None:
            current_value.append(token)
    if current_key is not None:
        result[current_key] = " ".join(current_value)
    return result


def parse_tres_gpu_count(tres: str) -> int | None:
    """GPUs in a Slurm TRES list such as CfgTRES / AllocTRES.

    The untyped 'gres/gpu=N' total wins; without it, typed entries
    ('gres/gpu:l40s=N') are summed. Returns None when the list names no GPU
    TRES at all, which is different from 0: an idle node's AllocTRES simply
    omits gres/gpu. 'gres/gpumem' and similar are not GPU counts.
    """
    untyped: int | None = None
    typed: int | None = None
    for item in tres.split(","):
        key, separator, value = item.strip().partition("=")
        if not separator:
            continue
        count = parse_int(value) or 0
        if key == "gres/gpu":
            untyped = (untyped or 0) + count
        elif key.startswith("gres/gpu:"):
            typed = (typed or 0) + count
    return untyped if untyped is not None else typed


def parse_gres_gpu_total(gres: str) -> int | None:
    """Total GPU count from a sinfo %G gres string.

    Handles typed gres and socket/index suffixes, e.g. 'gpu:l40s:3(S:0-1)'
    (AIRE), 'gpu:nvidia_h200:8(S:0-1)' (Calder), 'gpu:4(IDX:0-3)',
    'gpu:a100:4(S:0,2)', and comma-joined lists like 'gpu:a100:4,mps:400'.
    Parenthesised groups are removed from the whole string BEFORE splitting
    on ',': a socket or index list may itself contain commas. Agrees with
    slurmGPUTotal in Sources/HPCCore/GPUAccounting.swift (the contract test
    compares the two on the fixture's nodes).
    """
    cleaned = gres.strip()
    if not cleaned or cleaned in {"(null)", "N/A", "n/a"}:
        return None
    cleaned = re.sub(r"\([^)]*\)", "", cleaned)
    total = 0
    found = False
    for entry in cleaned.split(","):
        entry = entry.strip()
        if not entry.startswith("gpu"):
            continue
        parts = entry.split(":")
        if parts[0] != "gpu":
            continue
        if len(parts) == 1:
            total += 1
            found = True
            continue
        match = re.match(r"(\d+)", parts[-1])
        if match:
            total += int(match.group(1))
            found = True
    return total if found else None


def parse_node_details(output: str) -> dict[str, dict[str, str]]:
    details: dict[str, dict[str, str]] = {}
    for line in nonempty_lines(output):
        values = parse_key_values(line)
        node_name = values.get("NodeName")
        if node_name:
            details[node_name] = values
    return details


def parse_remote_info(host: str, output: str) -> RemoteInfo:
    """Parse the 'hostname|user|cwd|time' line of the remote section.

    The working directory may contain '|' (it is a path), so hostname and
    user are split off from the left and the time from the right; neither
    end can contain the separator.
    """
    line = output.splitlines()[0] if output else ""
    left = line.split(FIELD_SEPARATOR, 2)
    if len(left) == 3:
        cwd, separator, remote_time = left[2].rpartition(FIELD_SEPARATOR)
        if separator:
            return RemoteInfo(
                host=host,
                hostname=left[0].strip(),
                user=left[1].strip(),
                cwd=cwd.strip(),
                remote_time=remote_time.strip(),
            )
    return RemoteInfo(host=host, hostname="", user="", cwd="", remote_time="")


