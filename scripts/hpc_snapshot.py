@dataclass(frozen=True)
class ClusterSnapshot:
    # When the round trip returned (UTC, ISO 8601): the moment the data
    # describes, as closely as one timestamp can.
    collected_at: str
    cluster: ClusterInfo
    remote: RemoteInfo
    jobs: list[Job]
    partitions: list[PartitionSummary]
    nodes: list[NodeSummary]
    # None = not collected this time (--skip-storage, a stuck earlier
    # collection, or the round trip ended before the storage section): the
    # consumer keeps its previous rows. [] = collected, no volumes.
    storage: list[StorageSummary] | None
    errors: list[str]
    # Non-fatal issues (enrichment sections that failed, quota fallbacks);
    # consumers must never treat these as a failed refresh. Swift's Codable
    # ignores unknown keys, so older app builds are unaffected.
    warnings: list[str] = field(default_factory=list)
    # True when storage was deliberately not collected: --skip-storage, or an
    # earlier collection's df/quota/lfs still stuck on the login node.
    storage_skipped: bool = False
    # When collection began (before the socket probe), UTC ISO 8601.
    started_at: str | None = None
    # Wall time of the whole collection (probe + round trips), milliseconds.
    duration_ms: int | None = None
    # Milliseconds per step: the local "probe" and "round_trip" (plus
    # "jobs_fallback_round_trip" when it ran), and one entry per remote
    # section measured on the login node's clock ("prelude", "remote",
    # "partitions", "nodes", "jobs_json", "node_details", "storage", ...).
    timings: dict[str, int] = field(default_factory=dict)


