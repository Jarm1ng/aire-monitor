def summarize_volume(
    volume: StorageVolume,
    block: dict[str, list[str]] | None,
) -> tuple[StorageSummary | None, list[str]]:
    """Build one storage row (or None to omit it) plus any warnings.

    Only proof of absence omits an optional volume: the remote side printed
    __HPC-TRIED__ (no candidate exists). A block that never arrived, or was
    cut before saying either way, is "not-collected" for optional and
    required volumes alike, so a slow Lustre cannot make Calder's Flash row
    (and its trend series) silently vanish and reappear.
    """
    warnings: list[str] = []
    block = block or {}
    path = first_nonempty(block.get("PATH"))
    stalled = first_nonempty(block.get("STALLED"))
    # The TRIED marker alone is a verdict (the shell decided before printing
    # it); a PATH or STALLED marker whose value line never arrived is not.
    if not path and not stalled and "TRIED" not in block:
        # No verdict for this volume: the round trip ended first, which the
        # section-level warning already reports. Never show the unexpanded
        # template ("/scratch-calder/users/$USER") as if it were a path.
        return unavailable_volume(volume, "", "not-collected"), warnings

    if stalled:
        warnings.append(
            f"Storage '{volume.label}': {stalled} did not answer in time "
            "(the filesystem may be hung); usage not read"
        )
        return unavailable_volume(volume, stalled, "no-figures"), warnings

    if not path:
        if volume.optional:
            return None, warnings
        tried = [line.strip() for line in block.get("TRIED", []) if line.strip()]
        shown = ", ".join(tried) if tried else ", ".join(volume.paths)
        warnings.append(f"Storage '{volume.label}': no directory found (tried {shown})")
        return unavailable_volume(volume, tried[0] if tried else "", "missing"), warnings

    df = parse_df_block(block.get("DF"))
    df_source = str(df.get("filesystem_text") or "")
    mount = first_nonempty(block.get("MOUNT")) or str(df.get("mount") or "")
    quota_lines = block.get("QUOTA")

    quota: dict[str, object] = {}
    quota_type = "df"
    project_id: int | None = None
    source = "df"
    if volume.quota == "nfs":
        quota = parse_nfs_quota(quota_lines, filesystem=df_source, mount=mount)
        if quota.get("used_gb") is not None:
            quota_type, source = "nfs", "quota"
    elif volume.quota == "lustre":
        raw_project = first_nonempty(block.get("PROJECT")) or ""
        project_number = int(raw_project) if raw_project.isdigit() else 0
        quota = parse_lfs_quota(quota_lines, mount=mount)
        if quota.get("used_gb") is not None:
            source = "lfs quota"
            if project_number > 0:
                quota_type, project_id = "lustre-project", project_number
            else:
                quota_type = "lustre-user"

    if quota_type == "df":
        if df.get("total_gb") is None and df.get("used_gb") is None:
            # Neither quota nor df produced a figure: the volume was cut off
            # mid-block (round trip ran out of budget), or df itself failed
            # or timed out on a slow filesystem. There are no totals to show,
            # so say "unavailable" rather than a df row full of nulls.
            warnings.append(
                f"Storage '{volume.label}': no usage figures for {path} "
                "(df/quota gave no output; the filesystem may be slow)"
            )
            return unavailable_volume(volume, path, "no-figures", filesystem=df_source, mount=mount), warnings
        if volume.quota != "none":
            warnings.append(
                f"Storage '{volume.label}': {volume.quota} quota unavailable for {path}; "
                "showing filesystem totals from df"
            )
        used = df.get("used_gb")
        limit = df.get("total_gb")
        return StorageSummary(
            label=volume.label,
            path=path,
            filesystem=df_source or mount,
            source="df",
            used_gb=used,  # type: ignore[arg-type]
            quota_gb=None,
            limit_gb=limit,  # type: ignore[arg-type]
            available_gb=df.get("available_gb"),  # type: ignore[arg-type]
            used_percent=df.get("used_percent"),  # type: ignore[arg-type]
            file_count=None,
            file_quota=None,
            file_limit=None,
            over_quota=False,
            quota_type="df",
            project_id=None,
            mount=mount,
            optional=volume.optional,
        ), warnings

    if quota.get("inaccurate"):
        warnings.append(
            f"Storage '{volume.label}': lfs marked the quota figures for {path} as inaccurate "
            "(some Lustre servers did not answer); usage may be under-reported"
        )
    used = quota.get("used_gb")
    limit = quota.get("limit_gb") or quota.get("quota_gb")
    available = None
    if limit is not None and used is not None:
        available = max(limit - used, 0)  # type: ignore[operator]
    elif df.get("available_gb") is not None:
        available = df.get("available_gb")
    return StorageSummary(
        label=volume.label,
        path=path,
        filesystem=df_source or str(quota.get("filesystem_text") or "") or mount,
        source=source,
        used_gb=used,  # type: ignore[arg-type]
        quota_gb=quota.get("quota_gb"),  # type: ignore[arg-type]
        limit_gb=limit,  # type: ignore[arg-type]
        available_gb=available,  # type: ignore[arg-type]
        used_percent=storage_percent(used, limit, df.get("used_percent")),  # type: ignore[arg-type]
        file_count=quota.get("file_count_int"),  # type: ignore[arg-type]
        file_quota=quota.get("file_quota_int"),  # type: ignore[arg-type]
        file_limit=quota.get("file_limit_int"),  # type: ignore[arg-type]
        over_quota=bool(quota.get("over_quota", False)),
        quota_type=quota_type,
        project_id=project_id,
        mount=mount,
        optional=volume.optional,
    ), warnings


def storage_busy(output: str) -> bool:
    return any(line.strip() == STORAGE_BUSY_MARKER for line in output.splitlines())


def parse_storage(
    output: str,
    volumes: list[StorageVolume],
) -> tuple[list[StorageSummary] | None, list[str]]:
    """Parse the storage section for every spec volume, in spec order.

    Returns None for the rows when the remote side skipped storage because
    an earlier collection is still stuck (STORAGE_BUSY_MARKER).
    """
    if storage_busy(output):
        return None, [
            "Storage not collected: a df/quota/lfs from an earlier refresh is still stuck "
            "on the login node (a hung filesystem?); it is retried on later refreshes"
        ]
    blocks = split_storage_blocks(output)
    storage: list[StorageSummary] = []
    warnings: list[str] = []
    for index, volume in enumerate(volumes):
        summary, volume_warnings = summarize_volume(volume, blocks.get(index))
        warnings.extend(volume_warnings)
        if summary is not None:
            storage.append(summary)
    return storage, warnings


def nonempty_lines(output: str) -> Iterable[str]:
    for line in output.splitlines():
        stripped = line.strip()
        if stripped:
            yield stripped


# ---------------------------------------------------------------------------
# The remote script
# ---------------------------------------------------------------------------


# Shared start of every remote script. section() is printed BEFORE a
# section's command runs and finish() after it, with the exit status and the
# login node's clock (date +%s.%N; whole seconds where %N is unsupported), so
# a cut round trip names the section it was cut in and every refresh records
# where its time went.
REMOTE_PRELUDE = r"""
section() { printf '\n=====HPC-SECTION:%s=====\n' "$1"; }
finish() {
    printf '\n=====HPC-STATUS:%s:%s=====\n' "$1" "$2"
    printf '=====HPC-TIME:%s:%s=====\n' "$1" "$(date +%s.%N 2>/dev/null)"
}
printf '=====HPC-TIME:start:%s=====\n' "$(date +%s.%N 2>/dev/null)"

# A non-interactive `ssh host cmd` shell may not have run the login profile
# that puts Slurm/Lustre tools on PATH. Only if squeue is missing, source the
# system profile with all of its output discarded (so a chatty profile.d
# script cannot corrupt the section stream). Never touches user dotfiles.
if ! command -v squeue >/dev/null 2>&1; then
    . /etc/profile >/dev/null 2>&1 || true
fi
[ -n "${USER:-}" ] || USER=$(id -un 2>/dev/null)
# Slurm abbreviates long array task lists to 64 characters ("1,3,5,...")
# unless told otherwise; 0 = print them in full, so queued tasks can be
# counted.
SLURM_BITSTR_LEN=0
export SLURM_BITSTR_LEN
printf '=====HPC-TIME:prelude:%s=====\n' "$(date +%s.%N 2>/dev/null)"
"""

REMOTE_CORE_SECTIONS = r"""
section remote
printf '%s|%s|%s|%s\n' "$(hostname -f 2>/dev/null || hostname)" "$(whoami)" "$PWD" "$(date -Iseconds 2>/dev/null || date)"
finish remote $?

section partitions
# %l (partition time limit) is last so older parsers see an 8-field prefix.
sinfo -h -o '%P|%a|%D|%t|%G|%c|%m|%f|%l'
finish partitions $?

section nodes
# %E (Reason) is last: it is free text and may contain '|'.
sinfo -N -h -o '%N|%P|%t|%C|%m|%G|%f|%E'
finish nodes $?

section jobs_json
hpc_jobs_json=$(squeue -u "$USER" --json 2>/dev/null)
hpc_jobs_json_rc=$?
if [ "$hpc_jobs_json_rc" -eq 0 ]; then
    # squeue pretty-prints. A JSON string cannot hold a raw newline, so any
    # leading whitespace on a line is indentation and can go (about a third
    # of the bytes).
    printf '%s\n' "$hpc_jobs_json" | sed 's/^[[:space:]]*//'
fi
finish jobs_json $hpc_jobs_json_rc
# The pipe-format listing and the per-job scontrol loop are only a fallback
# for a Slurm without a usable --json (or a failed call).
hpc_jobs_fallback=1
if [ "$hpc_jobs_json_rc" -eq 0 ]; then
    case $hpc_jobs_json in
    *'"jobs"'*) hpc_jobs_fallback=0 ;;
    esac
fi
hpc_jobs_json=''
"""

# The pipe-format jobs listing (core when used). The listing is kept in
# $hpc_jobs for the job_details loop.
REMOTE_JOBS_PIPE_SECTION = r"""
section jobs
hpc_jobs=$(squeue -u "$USER" -h -o '%i|%P|%j|%u|%T|%M|%l|%D|%R')
hpc_jobs_rc=$?
printf '%s\n' "$hpc_jobs"
finish jobs $hpc_jobs_rc
"""

# One scontrol per job of the listing above. Querying per id tolerates
# vanished jobs: a job finishing between squeue and scontrol would otherwise
# fail the WHOLE list with "Invalid job id specified". A pending array
# remainder ('123_[4-9%2]') is queried by its array id, which lists every
# element of that array.
REMOTE_JOB_DETAILS_SECTION = r"""
section job_details
for hpc_job in $(printf '%s\n' "$hpc_jobs" | awk -F'|' '{ id = $1; sub(/_\[.*/, "", id); if (id ~ /^[0-9][0-9_+]*$/) print id }' | sort -u); do
    scontrol show job -o "$hpc_job" 2>/dev/null || true
done
finish job_details 0
"""

REMOTE_NODE_DETAILS_SECTION = r"""
section node_details
scontrol show node -o
finish node_details $?
"""


def _indent(text: str, prefix: str = "    ") -> str:
    return "\n".join(prefix + line if line.strip() else line for line in text.strip("\n").splitlines())


def _compact_shell(label: str, parts: list[str]) -> str:
    """Join script parts, dropping blank and comment-only lines.

    The script is sent as the ssh command on every refresh (every 10 s per
    cluster), so its explanatory comments would be pure upload; they are for
    readers of this file. Safe because no multi-line quoted string in these
    scripts has a line starting with '#'. The first line names the round
    trip, which also makes a stuck one easy to recognise in `ps` on the
    login node.
    """
    lines = [f"# hpc-round-trip: {label}"]
    for part in parts:
        for line in part.splitlines():
            if line.strip() and not line.lstrip().startswith("#"):
                lines.append(line)
    return "\n".join(lines) + "\n"


def build_remote_script(
    volumes: list[StorageVolume],
    budget: int = DEFAULT_TIMEOUT,
    include_storage: bool = True,
) -> str:
    """The single round trip's script.

    Core sections first, so a slow enrichment section can only ever cost
    itself: remote, partitions, nodes, jobs_json (+ the pipe 'jobs' fallback
    when the JSON is unusable), then node_details (+ 'job_details' with the
    fallback), then storage unless the caller skips it this time.
    """
    parts = [
        REMOTE_PRELUDE,
        REMOTE_CORE_SECTIONS,
        'if [ "$hpc_jobs_fallback" -eq 1 ]; then',
        _indent(REMOTE_JOBS_PIPE_SECTION),
        "fi",
        REMOTE_NODE_DETAILS_SECTION,
        'if [ "$hpc_jobs_fallback" -eq 1 ]; then',
        _indent(REMOTE_JOB_DETAILS_SECTION),
        "fi",
    ]
    if include_storage:
        parts.append("section storage")
        parts.append(build_storage_script(volumes, budget))
        parts.append("finish storage 0")
    return _compact_shell("snapshot", parts)


def build_jobs_fallback_script() -> str:
    """Second round trip, run only when the --json payload passed the remote
    sanity check but could not be used locally: the pipe listing and its
    scontrol details, nothing else."""
    return _compact_shell("jobs-fallback", [
        REMOTE_PRELUDE,
        REMOTE_JOBS_PIPE_SECTION,
        REMOTE_JOB_DETAILS_SECTION,
    ])


# ---------------------------------------------------------------------------
# Assembling a snapshot from the remote output
# ---------------------------------------------------------------------------


# Core sections make or break a snapshot: their failure means the connection
# or Slurm itself is unusable, so it surfaces as an error (the app treats any
# error as a failed refresh). The jobs requirement is met by a usable
# jobs_json OR a clean pipe-format 'jobs' section (see resolve_jobs).
# Enrichment sections only add detail on top of a perfectly good snapshot —
# their failure must never mark the session offline, so it is reported as a
# warning instead. job_details is expected only with the pipe fallback, and
# storage only when it was not skipped.
CORE_SECTIONS = (
    "remote",
    "partitions",
    "nodes",
)

ENRICHMENT_SECTIONS = (
    "node_details",
    "job_details",
    "storage",
)


def _is_marker(line: str, prefix: str) -> bool:
    return line.startswith(prefix) and line.endswith(MARKER_SUFFIX)


def split_sections(output: str) -> tuple[dict[str, str], dict[str, int]]:
    """{section: text} and {section: exit status}, both in output order."""
    sections: dict[str, list[str]] = {}
    statuses: dict[str, int] = {}
    current: str | None = None
    for line in output.splitlines():
        stripped = line.strip()
        if _is_marker(stripped, SECTION_MARKER_PREFIX):
            current = stripped[len(SECTION_MARKER_PREFIX):-len(MARKER_SUFFIX)]
            sections[current] = []
            continue
        if _is_marker(stripped, STATUS_MARKER_PREFIX):
            body = stripped[len(STATUS_MARKER_PREFIX):-len(MARKER_SUFFIX)]
            name, _, code = body.rpartition(":")
            try:
                statuses[name] = int(code)
            except ValueError:
                pass
            current = None
            continue
        if _is_marker(stripped, TIME_MARKER_PREFIX):
            continue
        if current is not None:
            sections[current].append(line)
    joined = {name: "\n".join(lines).strip("\n") for name, lines in sections.items()}
    return joined, statuses


REMOTE_CLOCK_RE = re.compile(r"(\d+)(?:\.(\d+))?")


def parse_remote_clock(stamp: str) -> float | None:
    """'1760000000.123456789' -> seconds; '1760000000.N' (a date without
    %N) -> whole seconds; anything else -> None."""
    match = REMOTE_CLOCK_RE.match(stamp.strip())
    if not match:
        return None
    seconds = float(match.group(1))
    if match.group(2):
        seconds += float("0." + match.group(2))
    return seconds


def section_timings(output: str) -> dict[str, int]:
    """Milliseconds per remote section from consecutive TIME markers.

    Each 'start' marker begins a round trip; every later marker is charged
    the time since the previous one (a section repeated across round trips
    accumulates). Measured on the login node's clock, so local clock skew
    does not matter.
    """
    timings: dict[str, int] = {}
    previous: float | None = None
    for line in output.splitlines():
        stripped = line.strip()
        if not _is_marker(stripped, TIME_MARKER_PREFIX):
            continue
        name, _, stamp = stripped[len(TIME_MARKER_PREFIX):-len(MARKER_SUFFIX)].rpartition(":")
        seconds = parse_remote_clock(stamp)
        if not name or seconds is None:
            previous = None
            continue
        if name != "start" and previous is not None:
            timings[name] = timings.get(name, 0) + max(int(round((seconds - previous) * 1000)), 0)
        previous = seconds
    return timings


