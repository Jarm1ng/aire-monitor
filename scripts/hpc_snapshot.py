ARRAY_TASK_TOKEN_RE = re.compile(r"^(\d+)(?:-(\d+)(?::(\d+))?)?$")
# squeue %i for a pending array remainder ('8248307_[2-5%4]') and for one
# array task ('8248307_0').
PIPE_ARRAY_REMAINDER_RE = re.compile(r"^(\d+)_\[([^\]]*)\]$")
PIPE_ARRAY_TASK_RE = re.compile(r"^(\d+)_(\d+)$")


def count_array_tasks(tasks: str) -> int | None:
    """Count the ids in a Slurm task list: '0-58' -> 59, '1-9:2' -> 5,
    '1,3,5-7' -> 5. None when the list is empty, malformed or truncated
    ('1,3,5...', which Slurm prints when SLURM_BITSTR_LEN cuts it short)."""
    text = tasks.strip()
    if not text:
        return None
    total = 0
    for token in text.split(","):
        match = ARRAY_TASK_TOKEN_RE.match(token.strip())
        if not match:
            return None
        first = int(match.group(1))
        if match.group(2) is None:
            total += 1
            continue
        last = int(match.group(2))
        step = int(match.group(3) or 1)
        if last < first or step < 1:
            return None
        total += (last - first) // step + 1
    return total


def parse_array_task_spec(spec: str) -> tuple[str, int | None, int | None]:
    """'0-58%4' -> ('0-58', 4, 59): the queued task ids without the throttle,
    the '%N' throttle, and the number of queued tasks."""
    tasks, separator, raw_throttle = spec.strip().partition("%")
    throttle = parse_int(raw_throttle) if separator else None
    tasks = tasks.strip()
    return tasks, (throttle if throttle else None), count_array_tasks(tasks)


@dataclass(frozen=True)
class JobIdentity:
    """A job's normalised id plus its array membership (see Job)."""

    job_id: str
    array_job_id: int | None = None
    array_pending_tasks: str | None = None
    array_throttle: int | None = None
    pending_task_count: int | None = None


def array_remainder_identity(array_job_id: int, task_spec: str, throttle: int | None = None) -> JobIdentity:
    tasks, spec_throttle, count = parse_array_task_spec(task_spec)
    return JobIdentity(
        job_id=str(array_job_id),
        array_job_id=array_job_id,
        array_pending_tasks=tasks,
        array_throttle=spec_throttle or throttle,
        pending_task_count=count,
    )


def pipe_job_identity(raw_id: str) -> JobIdentity:
    """Normalise a squeue %i so the pipe fallback yields exactly the ids and
    array fields the JSON path does: '8248307_[2-5%4]' becomes job_id
    '8248307' with the remainder fields, '8248307_0' keeps its id and gains
    array_job_id. Anything else (plain ids, het jobs '123+0') is unchanged."""
    remainder = PIPE_ARRAY_REMAINDER_RE.match(raw_id)
    if remainder:
        return array_remainder_identity(int(remainder.group(1)), remainder.group(2))
    task = PIPE_ARRAY_TASK_RE.match(raw_id)
    if task:
        return JobIdentity(job_id=raw_id, array_job_id=int(task.group(1)))
    return JobIdentity(job_id=raw_id)


def parse_jobs(output: str, details_output: str = "", rejects: list[str] | None = None) -> list[Job]:
    """Parse the pipe-format fallback (squeue listing + scontrol records).

    `rejects` (when given) collects lines that could not be split, so the
    caller can warn instead of silently showing fewer jobs.
    """
    details_by_job = parse_job_details(details_output)
    jobs: list[Job] = []
    for line in nonempty_lines(output):
        fields = split_job_fields(line)
        if not fields:
            if rejects is not None:
                rejects.append(line)
            continue
        identity = pipe_job_identity(fields[0])
        base_id = identity.job_id.split("_", 1)[0].split(".", 1)[0]
        details = details_by_job.get(identity.job_id) or details_by_job.get(base_id) or {}
        jobs.append(
            Job(
                job_id=identity.job_id,
                partition=fields[1],
                name=fields[2],
                user=fields[3],
                state=fields[4],
                elapsed=fields[5],
                time_limit=fields[6],
                nodes=fields[7],
                reason_or_node_list=fields[8],
                submit_time=clean_optional(details.get("SubmitTime")),
                start_time=clean_optional(details.get("StartTime")),
                end_time=clean_optional(details.get("EndTime")),
                work_dir=clean_optional(details.get("WorkDir")),
                command=clean_optional(details.get("Command")),
                stdout_path=clean_optional(details.get("StdOut")),
                stderr_path=clean_optional(details.get("StdErr")),
                batch_host=clean_optional(details.get("BatchHost")),
                node_list=clean_optional(details.get("NodeList")),
                num_cpus=parse_int(details.get("NumCPUs", "")),
                num_tasks=parse_int(details.get("NumTasks", "")),
                req_tres=clean_optional(details.get("ReqTRES")),
                alloc_tres=clean_optional(details.get("AllocTRES")),
                tres_per_node=clean_optional(details.get("TresPerNode")),
                array_job_id=identity.array_job_id,
                array_pending_tasks=identity.array_pending_tasks,
                array_throttle=identity.array_throttle,
                pending_task_count=identity.pending_task_count,
            )
        )
    return jobs


def parse_job_details(output: str) -> dict[str, dict[str, str]]:
    """Index scontrol job records by every id squeue might report.

    Keys: the raw JobId, its base id (suffixes stripped), and — for array
    tasks — 'ArrayJobId_ArrayTaskId', which is how squeue %i reports them.
    A pending remainder's record has JobId = the array id, so the normalised
    remainder id finds it directly.
    """
    details: dict[str, dict[str, str]] = {}
    for line in nonempty_lines(output):
        values = parse_key_values(line)
        raw_job_id = values.get("JobId")
        if not raw_job_id:
            continue
        details[raw_job_id] = values
        base_id = raw_job_id.split("_", 1)[0].split(".", 1)[0]
        details.setdefault(base_id, values)
        array_job_id = clean_optional(values.get("ArrayJobId"))
        array_task_id = clean_optional(values.get("ArrayTaskId"))
        if array_job_id and array_task_id and array_task_id.isdigit():
            details[f"{array_job_id}_{array_task_id}"] = values
    return details


def clean_optional(value: str | None) -> str | None:
    if value is None:
        return None
    value = value.strip()
    if not value or value in {"N/A", "n/a", "(null)", "Unknown"}:
        return None
    return value


