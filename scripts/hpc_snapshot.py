#!/usr/bin/env python3
"""Collect a read-only Slurm snapshot from one HPC cluster over SSH.

This is the cluster-agnostic collector behind Leeds HPC Monitor. One
invocation talks to exactly one cluster (AIRE, Calder, ...); the app runs one
collector per cluster, each over that cluster's own SSH ControlMaster.

This script is intentionally local-only: it does not install anything on the
server, write remote files, submit jobs, or cancel jobs. It only runs
read-only Slurm, df, quota, lfs and ps commands through an SSH connection
that is already authenticated (an explicit ControlMaster socket, or a host
alias for manual testing). It never prompts for, receives, or forwards a
password.

All remote commands are batched into a single SSH round trip: a small POSIX
shell script prints section-delimited output which is parsed locally. Each
section carries its own exit status and finishing time, so one failing
command does not discard the rest of the snapshot and a slow refresh can be
attributed to the section that was slow. Sections run in this order: remote,
partitions, nodes, jobs_json, [jobs], node_details, [job_details], storage.
Jobs come from `squeue --json`; the pipe-format `jobs` listing and the
per-job `scontrol show job` loop (`job_details`) run only when the JSON is
unavailable, so a normal refresh costs a handful of slurmctld RPCs whatever
the number of jobs. When the JSON arrives but cannot be used locally, one
short second round trip fetches the pipe-format listing instead.

--timeout is the budget for the WHOLE collection (socket probe + round
trips), so the JSON is always printed before a caller watchdog slightly
longer than it fires. Storage runs last: a filesystem that stalls df/quota/lfs
past the budget costs only the storage rows (a warning), never the snapshot.
Quotas change slowly, so a caller may pass --skip-storage on most refreshes;
the snapshot then says `storage_skipped` and the caller keeps its last rows.

Storage is data-driven: --storage-spec describes each volume (label,
candidate directory templates, quota method) and the matching remote shell is
generated from it. Path templates may only reference $USER and $HOME; every
other character is shell-quoted literally (see render_path_template).

The output schema is versioned (`schema_version`, SCHEMA_VERSION below) and
pinned by a contract fixture that the Swift tests decode:
Tests/Fixtures/collector_snapshot.json, generated by
`scripts/tests/test_snapshot.py --write-fixture`. The unit tests live in
scripts/tests/test_snapshot.py; --self-test runs them.
"""

